// The truthful labels (WEB-13), in one place. The wording is the demonstration specification's label
// table (docs/product/storyboard.md, "Labels", X-16): a simulated outbox is a real prototype effect but
// not evidence of delivery, a replay is a scripted proposal, a fixture verdict says nothing about
// detection quality, the seeded operator is a development demonstration.
//
// Every label is derived from data the server sends (an action's `replaySource`, a control's
// `verdictSource`, an event's `effect`), never guessed by a page: the functions below return null when
// the data carries no mark, so an unmarked thing carries no label and a marked one always does.

export type LabelTone =
  | "simulation"
  | "replay"
  | "fixture"
  | "live"
  | "demonstration"
  | "estimate"
  | "synthetic"
  | "evidence";

export interface LabelText {
  /** Stable id for tests and styling hooks; never shown. */
  id: string;
  /** The compact badge text. */
  short: string;
  /** The full sentence the specification fixes. */
  full: string;
  tone: LabelTone;
}

