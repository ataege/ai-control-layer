/** The part of the full sentence after the compact text, for a view that shows both. */
export function labelDetail(label: LabelText): string {
  const separator = `${label.short}: `;
  return label.full.startsWith(separator) ? label.full.slice(separator.length) : label.full;
}

/** The prefix of an action's `replaySource` for a labelled replay (GO-36). */
const REPLAY_SOURCE_PREFIX = "labelled_replay:";

export interface ReplayLabel {
  label: LabelText;
  /** The replayed fixture's id, or null when the mark does not follow the labelled_replay:<id> form. */
  fixtureId: string | null;
}

/**
 * The label of a replayed proposal, from the action's (or event's) `replaySource`. null, undefined
 * and an empty string mean "a model proposal": no label. Any other value is a replay mark, so a mark
 * in an unexpected form still shows the label rather than hiding it.
 */
export function replayLabel(replaySource: string | null | undefined): ReplayLabel | null {
  if (replaySource === null || replaySource === undefined || replaySource === "") return null;
  if (replaySource.startsWith(REPLAY_SOURCE_PREFIX)) {
    const fixtureId = replaySource.slice(REPLAY_SOURCE_PREFIX.length);
    return { label: LABELS.replay, fixtureId: fixtureId === "" ? null : fixtureId };
  }
  return { label: LABELS.replay, fixtureId: null };
}

/**
 * The label of a semantic verdict, from a control assessment's `verdictSource`. "live" is a real local
 * model verdict and "fixture" a scripted one; null (a deterministic control, or a semantic check that
 * made no call) and anything unexpected carry no verdict label, so nothing is ever called live by
 * default.
 */
export function verdictSourceLabel(verdictSource: string | null | undefined): LabelText | null {
  if (verdictSource === "live") return LABELS.liveVerdict;
  if (verdictSource === "fixture") return LABELS.fixtureVerdict;
  return null;
}

/** The simulated-outbox label for an event whose `effect` is a queued outbox message, else null. */
export function outboxEffectLabel(effect: string | null | undefined): LabelText | null {
  return effect === "outbox_message_queued" ? LABELS.simulatedOutbox : null;
}

/**
 * The seeded operator's email (apps/api/src/auth/demo-operator-seed.ts). The session's `/me` carries
 * no flag for a development identity, so the label is derived from this seeded identity; a server
 * field would be better and is an open request.
 */
export const DEVELOPMENT_DEMONSTRATION_OPERATOR_EMAIL = "demo-operator@example.com";

export function isDevelopmentDemonstrationOperator(email: string | null | undefined): boolean {
  return (
    typeof email === "string" &&
    email.trim().toLowerCase() === DEVELOPMENT_DEMONSTRATION_OPERATOR_EMAIL
  );
}

export function developmentDemonstrationLabel(email: string | null | undefined): LabelText | null {
  return isDevelopmentDemonstrationOperator(email) ? LABELS.developmentDemonstration : null;
}

export interface EstimatedCost {
  /** The documented, versioned pricing rule behind an estimate; absent when there is none. */
  pricingRule?: string | null;
  /** True while a reservation has no settled usage: the amount is uncertain, never shown as zero. */
  unresolved?: boolean;
}

/**
 * The label of a cost figure: "Estimated" with its pricing rule, or "uncertain" for an unresolved
 * reservation. null means there is nothing honest to label, so the figure should not be shown (the
 * specification: "Estimated, with the pricing rule, or not shown").
 */
export function estimatedCostLabel(cost: EstimatedCost): LabelText | null {
  if (cost.unresolved === true) {
    return {
      id: "uncertain_cost",
      short: "Uncertain",
      full: "Uncertain: an unresolved reservation, not a measured amount and not zero",
      tone: "estimate",
    };
  }
  const rule = cost.pricingRule?.trim();
  if (rule === undefined || rule === "") return null;
  return {
    id: "estimated_cost",
    short: "Estimated",
    full: `Estimated: priced by the rule ${rule}, not a provider invoice`,
    tone: "estimate",
  };
}

/** "Recording from build <id>" for a recording or screenshot, or null without a build id. */
export function recordingLabel(buildId: string | null | undefined): LabelText | null {
  const id = buildId?.trim();
  if (id === undefined || id === "") return null;
  return {
    id: "recording",
    short: "Recording",
    full: `Recording from build ${id}`,
    tone: "evidence",
  };
}
