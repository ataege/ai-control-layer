export class CreateServiceRoles1791050000000 implements MigrationInterface {
  name = "CreateServiceRoles1791050000000";

  public async up(queryRunner: QueryRunner): Promise<void> {
    for (const roleName of [API_ROLE, GATEWAY_ROLE]) {
      await queryRunner.query(
        `DO $$ BEGIN
          IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '${roleName}') THEN
            CREATE ROLE "${roleName}" NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
          END IF;
        END $$`,
      );
    }

    await this.grantAll(queryRunner, API_ROLE, API_GRANTS);
    await this.grantAll(queryRunner, GATEWAY_ROLE, GATEWAY_GRANTS);
  }

  public async down(queryRunner: QueryRunner): Promise<void> {
    // DROP OWNED revokes the role's privileges in this database (it owns nothing). DROP ROLE then
    // fails while a service is still connected as the role, or if another database granted it.
    for (const roleName of [GATEWAY_ROLE, API_ROLE]) {
      await queryRunner.query(`DROP OWNED BY "${roleName}"`);
      await queryRunner.query(`DROP ROLE "${roleName}"`);
    }
  }

  private async grantAll(
    queryRunner: QueryRunner,
    roleName: string,
    grants: Array<[string, string, string]>,
  ): Promise<void> {
    const schemaNames = [...new Set(grants.map(([schemaName]) => schemaName))];
    for (const schemaName of schemaNames) {
      await queryRunner.query(`GRANT USAGE ON SCHEMA "${schemaName}" TO "${roleName}"`);
    }
    for (const [schemaName, tableName, privileges] of grants) {
      await queryRunner.query(
        `GRANT ${privileges} ON "${schemaName}"."${tableName}" TO "${roleName}"`,
      );
    }
  }
}
