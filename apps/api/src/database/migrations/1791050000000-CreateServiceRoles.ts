// infrastructure role on 2026-10-03. It builds on migrations that are drafts themselves: the
// runtime and demo drafts on feat/35-fixtures-and-tests (SH-16, SH-17, SH-24, SH-27, SH-44) and
// the control catalog on feat/fd-catalog-and-tests (API-31). It sorts after all of them and fails
// if one of their tables is missing.
//
// Decision 2: explicit, narrow privileges per service; the Go executor commits effects, lineage
// and completion on one connection, so the gateway is one role.
//
// - Roles are cluster-wide, so they are created only if missing. They are created NOLOGIN and
//   without a password: until a password is set from .env (follow-up below) nobody can log in as
//   them. Running this migration needs CREATEROLE (the image's POSTGRES_USER is a superuser).
// - Grants are explicit per table, with no default privileges: every later migration that adds a
//   table must grant on it. No role gets DELETE, TRUNCATE or DDL; the migration user stays the
//   owner of every object, and the seed and reset commands run as that user.
// - Where a draft trigger already freezes rows, the grant matches it (no UPDATE).
//
// Not granted yet, because the tables do not exist or the decision is open:
// - gateway read on the app task, policy and revocation records and on the identity records
//   behind operator and reviewer authority (decisions 4 and 7, SH-03, SH-38);
// - API read on runtime (`read path`), on form-option records (`form options`) and on the stored
//   report (`stored report read`);
// - lineage tables (`report storage`); UPDATE of a report title (`rename operation`).
//
// Follow-up, not wired here (proposal): POSTGRES_API_PASSWORD and POSTGRES_GATEWAY_PASSWORD,
// generated by `pnpm run setup` (scripts/lib/generated-secrets.mjs, which also puts them in the
// smoke leak checks), set by a root script such as `pnpm db:roles:password` running
// ALTER ROLE ... WITH LOGIN PASSWORD after the migrations, and read by each service's own
